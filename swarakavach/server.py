@app.get("/demo/list")
def demo_list():
    """The finale demo calls (scenario audio generated by scripts/make_demo_data.py)."""
    import re as _re

    calls = []
    if DEMO_DIR.exists():
        for p in sorted(DEMO_DIR.glob("*.wav")):
            if _re.fullmatch(r"[A-Za-z0-9_]+", p.stem):
                calls.append({"id": p.stem, "name": DEMO_NAMES.get(p.stem, p.stem),
                              "url": f"/demo/audio/{p.stem}"})
    calls.sort(key=lambda c: c["id"])
    return {"calls": calls}


@app.get("/demo/audio/{name}")
def demo_audio(name: str):
    from fastapi.responses import FileResponse
    import re as _re

    if not _re.fullmatch(r"[A-Za-z0-9_]+", name):
        return JSONResponse(status_code=400, content={"error": "bad name"})
    p = DEMO_DIR / f"{name}.wav"
    if not p.exists():
        return JSONResponse(status_code=404, content={"error": "no such scenario"})
    return FileResponse(p, media_type="audio/wav")


@app.post("/v1/analyze")
async def analyze(body: bytes = Body(...), speaker_id: str | None = Query(None),
                  context: str | None = Query(None), transcript: str | None = Query(None),
                  asr: bool = Query(True)):
    try:
        wav = load_wav_bytes(body)
    except Exception as e:
        return JSONResponse(status_code=400, content={"error": f"bad audio: {e}"})
    ctx = json.loads(context) if context else None
    # scoring is CPU-heavy (all layers, every chunk) — keep the event loop free
    return await asyncio.to_thread(run_session, wav, ctx, speaker_id, None, transcript, asr)


@app.post("/v1/enroll")
async def enroll(body: bytes = Body(...), speaker_id: str = Query(...)):
    try:
        wav = load_wav_bytes(body)
    except Exception as e:
        return JSONResponse(status_code=400, content={"error": f"bad audio: {e}"})
    return await asyncio.to_thread(speaker.enroll, speaker_id, wav)


@app.get("/v1/sessions/{sid}")
def session(sid: str):
    if sid not in SESSIONS:
        return JSONResponse(status_code=404, content={"error": "unknown session"})
    return SESSIONS[sid]


@app.get("/v1/audit")
def audit_ledger():
    """Hash-chained incident ledger + chain integrity proof."""
    valid, broken = audit.verify_chain()
    return {"chain_valid": valid, "broken_at": broken if not valid else None,
            "records": audit.read()}


@app.post("/v1/audit/{incident_id}/decision")
def audit_decision(incident_id: str, decision: str = Query(...),
                   supervisor: str = Query(...)):
    """Append a supervisor decision for an incident (append-only)."""
    if not any(r.get("incident_id") == incident_id for r in audit.read()):
        return JSONResponse(status_code=404, content={"error": "unknown incident"})
    return audit.decision(incident_id, decision, supervisor)


@app.websocket("/v1/stream")
async def stream(ws: WebSocket, speaker_id: str | None = Query(None),
                 context: str | None = Query(None), transcript: str | None = Query(None)):
    """Live stream protocol: client sends binary PCM16LE 16k-mono frames;
    server replies per-chunk risk events; text frame 'END' finalizes.
    Without an explicit transcript, a rolling ASR transcriber feeds the intent
    layer from the live audio (4 s rolling windows)."""
    await ws.accept()
    engine = RiskEngine(json.loads(context) if context else None)
    sid = uuid.uuid4().hex[:12]
    buf = np.zeros(0, dtype=np.float32)
    trans = None
    if transcript is None and asr_mod.available():
        trans = asr_mod.StreamingTranscriber()
    try:
        while True:
            msg = await ws.receive()
            if msg.get("type") == "websocket.disconnect":
                break
            if (text := msg.get("text")) is not None:
                if text.strip().upper() == "END":
                    break
                continue
            data = msg.get("bytes")
            if not data:
                continue
            buf = np.concatenate([buf, pcm16_to_float(data)])
            while len(buf) >= config.CHUNK_SAMPLES:
                chunk, buf = buf[: config.CHUNK_SAMPLES], buf[config.CHUNK_SAMPLES:]
                live_tr = transcript
                if trans is not None:
                    utt = await asyncio.to_thread(trans.feed, chunk)
                    if utt:
                        live_tr = " ".join(trans.text_parts)
                ev = engine.update({
                    "artifact": artifact.score(chunk),
                    "ssl": await asyncio.to_thread(ssl_detector.score, chunk),
                    "speaker": speaker.score(speaker_id, chunk) if speaker_id else None,
                    "context": ctx_engine.score(engine.context),
                    "intent": intent.score(live_tr),
                })
                if utt:
                    ev["transcript_delta"] = utt
                await ws.send_text(json.dumps({"session_id": sid, **ev}))
        verdict = engine.verdict()
        final_tr = transcript or (" ".join(trans.text_parts) if trans else None)
        SESSIONS[sid] = {"session_id": sid, "ts": time.time(), "context": engine.context,
                         "speaker_id": speaker_id, "verdict": verdict,
                         "transcript": final_tr,
                         "trajectory": engine.trajectory, "layers": engine.layer_history}
        if verdict["level"] in ("HIGH", "CRITICAL"):
            audit.incident(SESSIONS[sid], model_version=app.version)
        if "INCIDENT_WEBHOOK" in verdict["actions"] and config.WEBHOOK_URL:
            _webhook(SESSIONS[sid])
        await ws.send_text(json.dumps({"session_id": sid, "final": True, **verdict}))
    except WebSocketDisconnect:
        pass
